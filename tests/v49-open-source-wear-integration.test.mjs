import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const watch=n=>read('watch/src/main/java/com/cobrachris/watchvibrationpoc/'+n+'.java');
test('optional Wear tile and complication use durable planned alarms',()=>{
 const tile=watch('SanftweckerNextAlarmTileService');
 const complication=watch('SanftweckerNextAlarmComplicationService');
 const notifier=watch('WatchAlarmPresentation');
 const schedule=watch('WatchScheduleStore');
 const manifest=read('watch/src/main/AndroidManifest.xml');
 assert.match(tile,/extends TileService/);
 assert.match(tile,/WatchScheduleStore\.next\(this\)/);
 assert.match(tile,/CLICK_STOP/);
 assert.match(tile,/CLICK_SNOOZE/);
 assert.match(tile,/snooze>0/);
 assert.match(tile,/WatchAlarmService\.STOP/);
 assert.match(tile,/WatchAlarmService\.SNOOZE/);
 assert.match(complication,/extends ComplicationDataSourceService/);
 assert.match(complication,/ComplicationType\.SHORT_TEXT/);
 assert.match(complication,/ComplicationType\.LONG_TEXT/);
 assert.match(complication,/WatchScheduleStore\.next\(this\)/);
 assert.match(notifier,/TileService\.getUpdater/);
 assert.match(notifier,/ComplicationDataSourceUpdateRequester/);
 assert.match(schedule,/WatchAlarmPresentation\.changed\(c\)/);
 assert.match(manifest,/BIND_TILE_PROVIDER/);
 assert.match(manifest,/BIND_COMPLICATION_PROVIDER/);
 assert.match(manifest,/SUPPORTED_TYPES/);
});
test('phone sends a true scheduling result to the requesting Wear node',()=>{
 const listener=read('alarm/src/main/java/com/cobrachris/sanftwecker/WearPhoneListener.java');
 const scheduler=read('alarm/src/main/java/com/cobrachris/sanftwecker/TimerScheduler.java');
 const packet=watch('WatchTimerProtocol');
 assert.match(listener,/applied=TimerScheduler\.extendFinished/);
 assert.match(listener,/event\.getSourceNodeId\(\)/);
 assert.match(listener,/TimerWatchPacket\.EXTEND_RESULT/);
 assert.match(scheduler,/before\.state!=TimerEntry\.FINISHED/);
 assert.match(scheduler,/before\.dueWallMs!=expectedDue/);
 assert.match(packet,/EXTEND_RESULT/);
});
test('Watch rejects stale ACK and only announces phone-confirmed result',()=>{
 const feedback=watch('WatchTimerExtensionFeedback');
 const receiver=watch('SanftweckerWearListener');
 const ui=watch('WatchTimerRingActivity');
 const service=watch('WatchTimerAlertService');
 assert.match(feedback,/pending\.getInt\("id",0\)!=id/);
 assert.match(feedback,/pending\.getLong\("due",0\)!=due/);
 assert.match(feedback,/pending\.getLong\("amount",0\)!=amount/);
 assert.match(feedback,/applied\?"Timer verlängert":"Timer nicht verlängert"/);
 assert.match(receiver,/WatchTimerProtocol\.EXTEND_RESULT\.equals\(path\)/);
 assert.match(ui,/WatchTimerExtensionFeedback\.requested/);
 assert.match(ui,/receipt\.getString\("result","pending"\)/);
 assert.match(ui,/Timer am Handy erfolgreich verlängert/);
 assert.match(ui,/Timer nicht verlängert\. Bitte am Handy prüfen/);
 assert.match(service,/WatchTimerExtensionFeedback\.requested/);
});
test('foreign project is used as a licensed architectural reference, never an app replacement',()=>{
 const docs=read('docs/OPEN_SOURCE_WEAR_INTEGRATION_V49.md');
 assert.match(docs,/AlarmClockXtreme/);
 assert.match(docs,/Apache-2\.0/);
 assert.match(docs,/kein Quellcode direkt kopiert/);
 const gradle=read('watch/build.gradle');
 assert.match(gradle,/androidx\.wear\.tiles:tiles/);
 assert.match(gradle,/watchface-complications-data-source/);
});
